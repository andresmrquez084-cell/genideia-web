-- Perfiles: cada uno lee el suyo; solo el admin lee todos y los edita. Nadie se cambia el rol solo.
drop policy if exists gen_hub_profiles_select on public.gen_hub_profiles;
create policy gen_hub_profiles_select on public.gen_hub_profiles for select to authenticated
  using (auth_user_id = auth.uid() or public.gen_hub_is_admin());
drop policy if exists gen_hub_profiles_admin_write on public.gen_hub_profiles;
create policy gen_hub_profiles_admin_write on public.gen_hub_profiles for update to authenticated
  using (public.gen_hub_is_admin()) with check (public.gen_hub_is_admin());

