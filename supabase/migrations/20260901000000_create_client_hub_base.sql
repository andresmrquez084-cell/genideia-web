-- Tablas con "visible_cliente": el cliente ve solo lo publicado.
do $$
declare t text;
begin
  foreach t in array array['gen_hub_presentaciones','gen_hub_actualizaciones','gen_hub_reuniones','gen_hub_entregables'] loop
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('create policy %I on public.%I for select to authenticated using (public.gen_hub_is_admin() or (visible_cliente and cliente_id = public.gen_hub_cliente_id()))', t || '_select', t);
    execute format('drop policy if exists %I on public.%I', t || '_admin_write', t);
    execute format('create policy %I on public.%I for all to authenticated using (public.gen_hub_is_admin()) with check (public.gen_hub_is_admin())', t || '_admin_write', t);
  end loop;
end $$;

