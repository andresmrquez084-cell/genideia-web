-- GENIDEIA Client Hub: esquema base (perfiles, clientes, proyectos, contratos y seguimiento).
-- Reconstruido el 19/11/2026 a partir de lo que usan /clientes, /clientes/portal y /clientes/admin,
-- porque el proyecto Supabase original se perdió sin migraciones.
-- Regla de acceso: el admin ve y edita todo; cada cliente solo lee lo suyo (y lo marcado visible).
-- Las altas de clientes y proyectos pasan por las funciones hub-create-client / hub-create-project.

-- ---------- Tablas ----------
create table if not exists public.gen_clientes (
  id              bigint generated by default as identity primary key,
  nombre          text not null,
  razon_social    text,
  rut             text,
  email           text,
  whatsapp        text,
  rep_nombre      text,
  tipo            text not null default 'empresa' check (tipo in ('empresa', 'persona')),
  nombre_portada  text,
  logo_url        text,
  estado          text not null default 'activo' check (estado in ('activo', 'pausado', 'finalizado')),
  creado_en       timestamptz not null default now()
);

create table if not exists public.gen_hub_profiles (
  auth_user_id    uuid primary key references auth.users(id) on delete cascade,
  username        text not null unique,
  nombre          text,
  role            text not null default 'client' check (role in ('admin', 'client')),
  activo          boolean not null default true,
  cliente_id      bigint references public.gen_clientes(id) on delete set null,
  empresa_nombre  text,
  video_url       text,
  creado_en       timestamptz not null default now(),
  check (role = 'admin' or cliente_id is not null)
);

create table if not exists public.gen_hub_proyectos (
  id              uuid primary key default gen_random_uuid(),
  cliente_id      bigint not null references public.gen_clientes(id) on delete cascade,
  nombre          text not null,
  alcance         text,
  precio          numeric(12,2),
  moneda          text not null default 'USD' check (moneda in ('USD', 'UYU')),
  plazo           text,
  forma_pago      text,
  garantia        text,
  estado          text not null default 'pendiente_firma'
                  check (estado in ('pendiente_firma', 'en_ejecucion', 'en_revision', 'implementado', 'pausado')),
  progreso        integer not null default 0 check (progreso between 0 and 100),
  proximo_paso    text,
  creado_en       timestamptz not null default now(),
  actualizado_en  timestamptz not null default now()
);

create table if not exists public.gen_hub_contratos (
  id                          uuid primary key default gen_random_uuid(),
  proyecto_id                 uuid not null references public.gen_hub_proyectos(id) on delete cascade,
  cliente_id                  bigint not null references public.gen_clientes(id) on delete cascade,
  numero                      text not null unique,
  contenido                   text not null,
  estado                      text not null default 'pendiente_firma' check (estado in ('pendiente_firma', 'firmado', 'anulado')),
  firma_cliente_data          text,
  firmado_cliente_nombre      text,
  firmado_cliente_documento   text,
  firmado_en                  timestamptz,
  creado_en                   timestamptz not null default now()
