-- ---------- Funciones de acceso ----------
create or replace function public.gen_hub_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.gen_hub_profiles
     where auth_user_id = auth.uid() and role = 'admin' and activo
  );
$$;

create or replace function public.gen_hub_cliente_id()
returns bigint language sql stable security definer set search_path = '' as $$
  select cliente_id from public.gen_hub_profiles
   where auth_user_id = auth.uid() and role = 'client' and activo
   limit 1;
$$;

revoke all on function public.gen_hub_is_admin() from public, anon;
revoke all on function public.gen_hub_cliente_id() from public, anon;
grant execute on function public.gen_hub_is_admin() to authenticated;
grant execute on function public.gen_hub_cliente_id() to authenticated;

