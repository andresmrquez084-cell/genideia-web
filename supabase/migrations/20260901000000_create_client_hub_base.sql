-- ---------- Firma de contrato por el cliente ----------
create or replace function public.gen_hub_sign_contract(
  p_contract_id uuid, p_signature text, p_signer_name text, p_signer_document text default null
) returns public.gen_hub_contratos
language plpgsql security definer set search_path = '' as $$
declare
  v_cliente bigint := public.gen_hub_cliente_id();
  v_row public.gen_hub_contratos;
begin
  if v_cliente is null then raise exception 'client_required'; end if;
  if coalesce(btrim(p_signer_name), '') = '' or char_length(p_signer_name) > 160 then raise exception 'signer_name_required'; end if;
  if p_signature is null or p_signature not like 'data:image/png;base64,%' or char_length(p_signature) > 1500000 then
    raise exception 'signature_invalid';
  end if;

  update public.gen_hub_contratos
     set estado = 'firmado',
         firma_cliente_data = p_signature,
         firmado_cliente_nombre = btrim(p_signer_name),
         firmado_cliente_documento = nullif(btrim(coalesce(p_signer_document, '')), ''),
         firmado_en = now()
   where id = p_contract_id and cliente_id = v_cliente and estado = 'pendiente_firma'
  returning * into v_row;

  if v_row.id is null then raise exception 'contract_not_available'; end if;

  update public.gen_hub_proyectos
     set estado = 'en_ejecucion', actualizado_en = now()
   where id = v_row.proyecto_id and estado = 'pendiente_firma';

  return v_row;
end $$;

revoke all on function public.gen_hub_sign_contract(uuid, text, text, text) from public, anon;
grant execute on function public.gen_hub_sign_contract(uuid, text, text, text) to authenticated;

