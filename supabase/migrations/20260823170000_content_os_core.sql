declare t text;
begin
  foreach t in array array[
    'content_os_workspaces','content_os_accounts','content_os_content','content_os_classifications',
    'content_os_metric_snapshots','content_os_account_snapshots','content_os_story_sequences','content_os_story_frames',
    'content_os_competitors','content_os_competitor_content','content_os_brand_personas','content_os_brand_scores',
    'content_os_experiments','content_os_patterns','content_os_recommendations','content_os_leads','content_os_lead_events',
    'content_os_followups','content_os_sales','content_os_attribution','content_os_value_scores','content_os_sync_runs'
  ] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

