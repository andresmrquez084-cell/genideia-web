create or replace view public.content_os_latest_metrics
with (security_invoker = true) as
select distinct on (m.content_id)
  m.*
from public.content_os_metric_snapshots m
order by m.content_id, m.captured_at desc;

create or replace view public.content_os_content_performance
with (security_invoker = true) as
select
  c.id,
  c.workspace_id,
  c.account_id,
  c.platform,
  c.external_content_id,
  c.title,
  c.caption,
  c.permalink,
  c.media_type,
  c.media_product_type,
  c.duration_seconds,
  c.published_at,
  cl.format,
  cl.topic,
  cl.hook_type,
  cl.intention,
  cl.expected_action,
  cl.audience,
  lm.views,
  lm.reach,
  lm.likes,
  lm.comments,
  lm.shares,
  lm.saves,
  lm.replies,
  lm.follows,
  lm.profile_visits,
  lm.avg_watch_time_ms,
  case when coalesce(lm.reach,0) > 0 then lm.saves::numeric / lm.reach else null end as save_rate,
  case when coalesce(lm.reach,0) > 0 then lm.shares::numeric / lm.reach else null end as share_rate,
  case when coalesce(lm.reach,0) > 0 then lm.follows::numeric / lm.reach else null end as follow_rate,
  case when coalesce(c.duration_seconds,0) > 0 and lm.avg_watch_time_ms is not null then (lm.avg_watch_time_ms / 1000.0) / c.duration_seconds else null end as watch_ratio
from public.content_os_content c
left join public.content_os_classifications cl on cl.content_id = c.id
left join public.content_os_latest_metrics lm on lm.content_id = c.id;

