create or replace function public.content_os_user_owns_workspace(target_workspace uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.content_os_workspaces w where w.id = target_workspace and w.owner_id = auth.uid());
$$;

